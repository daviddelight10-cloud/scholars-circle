export const DRUG_CLASSES = [...new Set(DRUGS.map((d) => d.class))].sort();

/** Find a drug by any name (brand, generic, or display name). */
export function findDrug(term) {
  const t = term.trim().toLowerCase();
  return DRUGS.find(
    (d) =>
      d.name.toLowerCase() === t ||
      d.generic.toLowerCase() === t ||
      (d.brands || []).some((b) => b.toLowerCase() === t)
  );
}

/** Name key used to match INTERACTION_PAIRS entries. */
export function drugKeys(d) {
  return [d.name, d.generic, ...(d.brands || [])].map((s) => s.toLowerCase());
}

/**
 * Pairwise interactions among a list of drug objects.
 * Returns [{ severity, note, drugA, drugB }] sorted major → moderate → minor.
 */
export function findInteractions(drugs) {
  const order = { major: 0, moderate: 1, minor: 2 };
  const out = [];
  for (let i = 0; i < drugs.length; i++) {
    for (let j = i + 1; j < drugs.length; j++) {
      const ka = drugKeys(drugs[i]);
      const kb = drugKeys(drugs[j]);
      for (const p of INTERACTION_PAIRS) {
        const hit =
          (ka.includes(p.a.toLowerCase()) && kb.includes(p.b.toLowerCase())) ||
          (ka.includes(p.b.toLowerCase()) && kb.includes(p.a.toLowerCase()));
        if (hit) {
          out.push({ severity: p.severity, note: p.note, drugA: drugs[i], drugB: drugs[j] });
          break;
        }
      }
    }
  }
  return out.sort((x, y) => order[x.severity] - order[y.severity]);
}
